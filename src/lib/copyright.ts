/** Generates an authorship/ownership record PDF for a song, matching the
 * Musicas project's own save_copyright_record (VideoSubtitles/app.py) --
 * same structure and tone, "Suno" swapped for "Jakebox" throughout per the
 * user's explicit instruction, plus a platform liability disclaimer (Jakebox
 * is not responsible for what a user creates with it), since this is a
 * multi-user product handing the record to each user for THEIR song, not a
 * personal declaration for one person's own catalog. */
import PDFDocument from "pdfkit";

export function generateCopyrightPdf(params: {
  title: string;
  authorName: string;
  publishDate: string; // YYYY-MM-DD
  lyricsText: string;
}): Promise<Buffer> {
  return new Promise((resolve, reject) => {
    const doc = new PDFDocument({ size: "LETTER", margin: 54 });
    const chunks: Buffer[] = [];
    doc.on("data", (chunk: Buffer) => chunks.push(chunk));
    doc.on("end", () => resolve(Buffer.concat(chunks)));
    doc.on("error", reject);

    doc.font("Helvetica-Bold").fontSize(16).text("Authorship & Copyright Record");
    doc.moveDown(0.6);

    doc.font("Helvetica").fontSize(11);
    doc.text(`Song title: ${params.title}`);
    doc.text(`Author: ${params.authorName}`);
    doc.text(`Publication date: ${params.publishDate}`);
    doc.moveDown(1);

    const statement =
      `This song and its lyrics were generated by ${params.authorName} using Jakebox's AI music ` +
      "generation platform. Per Jakebox's Terms of Service, output generated through the platform is " +
      "assigned to the user who created it; the user asserts original authorship and ownership of this " +
      "work as of the publication date stated above. Jakebox is not responsible for the originality, " +
      "accuracy, or legality of the prompts, lyrics, or generated output submitted or produced by its " +
      "users -- the user retains sole responsibility for ensuring they hold the necessary rights and " +
      "that the content does not infringe on any third party's rights.";
    doc.text(statement, { align: "left" });
    doc.moveDown(1.2);

    if (params.lyricsText.trim()) {
      doc.font("Helvetica-Bold").fontSize(12).text("Lyrics");
      doc.moveDown(0.3);
      doc.font("Helvetica").fontSize(10).text(params.lyricsText, { align: "left" });
    }

    doc.end();
  });
}
